import math
import time
import csv
import numpy as np
import scipy.special as sp_spec
from scipy.signal import find_peaks
import matplotlib.pyplot as plt


class AnnetUniversalPrimeEngineV3:
    def __init__(self, target_power_k: int = 12, window_size: int = 100_000, N_core: int = 30_000):
        if target_power_k < 2 or target_power_k > 14:
            raise ValueError("La puissance k doit être comprise entre 2 (10^2) et 14 (10^14).")
        self.k = int(target_power_k)
        self.x_target = 10 ** self.k
        self.window_size = int(window_size)
        self.N_core = int(N_core)

        # Base cellulaire minimale adaptative : sqrt(x_target + window_size)
        self.N_base = max(100_000, math.isqrt(self.x_target + self.window_size) + 100)
        self.N_full_sieve = self.x_target if self.k <= 8 else 100_000_000

        self.n_core = np.arange(1, self.N_core + 1, dtype=np.float64)
        self.u_core = np.log(self.n_core)

        self.is_prime_odd = None
        self.base_odd_primes = None
        self.Lambda_core = None
        self.kappa_core = None
        self.gamma_k = None
        self.lambda_k = None
        self.trace_grid = None
        self.trace_signal = None

    def initialize_cellular_core_and_base(self) -> dict:
        t0 = time.perf_counter()
        sieve_limit = max(self.N_base, self.N_full_sieve)
        half = sieve_limit // 2
        is_prime_odd = np.ones(half, dtype=np.uint8)
        is_prime_odd[0] = 0

        limit = math.isqrt(sieve_limit) // 2
        for i in range(1, limit + 1):
            if is_prime_odd[i]:
                p = 2 * i + 1
                is_prime_odd[(p * p) // 2::p] = 0

        self.is_prime_odd = is_prime_odd
        base_half = min(half, (self.N_base + 1) // 2)
        self.base_odd_primes = (2 * np.nonzero(is_prime_odd[:base_half])[0] + 1).astype(np.int64)
        t_sieve = time.perf_counter() - t0

        # Inversion triangulaire creuse de Cholesky-Möbius sur N_core
        Lambda = self.u_core.copy()
        for d in range(2, self.N_core // 2 + 1):
            val = Lambda[d - 1]
            if val > 1e-11:
                Lambda[2 * d - 1::d] -= val
        Lambda[Lambda < 1e-11] = 0.0
        self.Lambda_core = Lambda
        self.kappa_core = 2.0 * (1.0 + self.Lambda_core / np.sqrt(self.n_core))

        active_nodes = int(np.sum(self.Lambda_core[1:] > 1e-11))
        return {
            "sieve_time_sec": t_sieve,
            "ram_mb": self.is_prime_odd.nbytes / (1024 ** 2),
            "base_ram_mb": (base_half * 1) / (1024 ** 2),
            "base_primes_count": len(self.base_odd_primes),
            "active_nodes": active_nodes,
            "compression_pct": 100.0 * (1.0 - active_nodes / self.N_core)
        }

    def exact_pi(self, x_val: int) -> int:
        x_int = int(x_val)
        if x_int < 2:
            return 0
        return int(np.sum(self.is_prime_odd[:(x_int + 1) // 2])) + 1

    def extract_locked_spectral_reservoir(self, T_max: float = 210.0) -> dict:
        t0 = time.perf_counter()
        n_sub = self.n_core[1:]
        u_sub = self.u_core[1:]
        lam_sub = self.Lambda_core[1:]

        U_max = np.log(self.N_core)
        alpha = 3.2 / (U_max ** 2)
        window = np.exp(-alpha * (u_sub ** 2))

        mask_act = lam_sub > 1e-11
        u_act = u_sub[mask_act]
        w_disc = (lam_sub[mask_act] / np.sqrt(n_sub[mask_act])) * window[mask_act]

        N_low = 400
        u_low = u_sub[:N_low]
        w_cont_low = (-1.0 / np.sqrt(n_sub[:N_low])) * window[:N_low]
        u_high = np.linspace(np.log(N_low + 1.5), np.log(self.N_core + 0.5), 400)
        du_h = u_high[1] - u_high[0]
        w_cont_high = -np.exp(0.5 * u_high) * np.exp(-alpha * (u_high ** 2)) * du_h

        gamma_grid = np.linspace(10.0, T_max, 12000)
        trace_signal = -(np.cos(np.outer(gamma_grid, u_act)) @ w_disc) \
                       -(np.cos(np.outer(gamma_grid, u_low)) @ w_cont_low) \
                       -(np.cos(np.outer(gamma_grid, u_high)) @ w_cont_high)

        # Verrouillage strict N_op(T) = N_zeta(T)
        n_zeta_target = int(round((T_max / (2.0 * np.pi)) * np.log(T_max / (2.0 * np.pi * np.e)) + 7.0 / 8.0))
        peaks, _ = find_peaks(trace_signal, distance=28, prominence=0.25)
        if len(peaks) > n_zeta_target:
            top_idx = np.argsort(trace_signal[peaks])[::-1][:n_zeta_target]
            peaks = np.sort(peaks[top_idx])

        self.gamma_k = gamma_grid[peaks]
        self.lambda_k = -(self.gamma_k ** 2)
        self.trace_grid = gamma_grid
        self.trace_signal = trace_signal

        return {
            "elapsed_sec": time.perf_counter() - t0,
            "N_op": len(self.gamma_k),
            "N_zeta": n_zeta_target
        }

    @staticmethod
    def _compute_mobius(M_max: int = 45) -> np.ndarray:
        mu = np.zeros(M_max + 1, dtype=int)
        mu[1] = 1
        primes, is_comp = [], np.zeros(M_max + 1, dtype=bool)
        for i in range(2, M_max + 1):
            if not is_comp[i]:
                primes.append(i)
                mu[i] = -1
            for p in primes:
                if i * p > M_max:
                    break
                is_comp[i * p] = True
                if i % p == 0:
                    mu[i * p] = 0
                    break
                else:
                    mu[i * p] = -mu[i]
        return mu

    def predict_spectral_global(self, x_targets, M_mobius: int = 45) -> dict:
        x = np.atleast_1d(np.array(x_targets, dtype=np.float64))
        ln_x = np.log(x)
        li_2 = sp_spec.expi(np.log(2.0))

        mu = self._compute_mobius(M_mobius)
        R_x = np.zeros_like(x)
        for m in range(1, M_mobius + 1):
            if mu[m] != 0:
                R_x += (mu[m] / m) * (sp_spec.expi(ln_x / m) - li_2)

        pi_spec_fejer = np.zeros_like(x)
        T_dyn_used = np.zeros_like(x)
        T_max_avail = float(self.gamma_k[-1])

        for i, xv in enumerate(x):
            u_val = ln_x[i]
            T_dyn = min(T_max_avail, 55.0 + 8.5 * (u_val ** 1.35))
            T_dyn_used[i] = T_dyn
            modes_act = self.gamma_k[self.gamma_k <= T_dyn]

            w_fejer = np.clip(1.0 - 0.35 * ((modes_act / T_dyn) ** 2), 0.2, 1.0)
            amp = w_fejer / np.sqrt(0.25 + modes_act ** 2)

            phase_1 = u_val * modes_act - np.arctan(2.0 * modes_act)
            osc_1 = 2.0 * np.sqrt(xv) * np.sum(np.sin(phase_1) * amp) / u_val

            phase_2 = 0.5 * u_val * modes_act - np.arctan(2.0 * modes_act)
            osc_2 = -0.5 * (2.0 * (xv ** 0.25) * np.sum(np.sin(phase_2) * amp) / (0.5 * u_val))

            pi_spec_fejer[i] = R_x[i] - (osc_1 + osc_2)

        return {
            "x": x,
            "pi_spec_fejer": pi_spec_fejer,
            "R_x": R_x,
            "pi_li_classic": sp_spec.expi(ln_x) - li_2,
            "T_dyn": T_dyn_used
        }

    def scan_local_cellular_window(self, x_start: int, delta_x: int) -> dict:
        t0 = time.perf_counter()
        first_odd = x_start if (x_start % 2 == 1) else (x_start + 1)
        last_odd = (x_start + delta_x) if ((x_start + delta_x) % 2 == 1) else (x_start + delta_x - 1)
        n_odds = (last_odd - first_odd) // 2 + 1

        window_mask = np.ones(n_odds, dtype=np.uint8)
        max_val = first_odd + 2 * (n_odds - 1)
        sqrt_max = math.isqrt(max_val)

        idx_limit = np.searchsorted(self.base_odd_primes, sqrt_max, side="right")
        active_primes = self.base_odd_primes[:idx_limit]

        rem = first_odd % active_primes
        diff = (active_primes - rem) % active_primes
        is_even_mult = ((first_odd + diff) % 2 == 0)
        first_mult = first_odd + diff + np.where(is_even_mult, active_primes, 0)
        first_mult = np.maximum(first_mult, active_primes * active_primes)

        start_indices = (first_mult - first_odd) // 2
        valid = start_indices < n_odds
        for p, s_idx in zip(active_primes[valid], start_indices[valid]):
            window_mask[s_idx::p] = 0

        if first_odd == 1:
            window_mask[0] = 0

        local_primes = first_odd + 2 * np.nonzero(window_mask)[0]
        if x_start <= 2 <= x_start + delta_x:
            local_primes = np.insert(local_primes, 0, 2)

        p_float = local_primes.astype(np.float64)
        u_local = np.log(p_float)
        kappa_peaks = 2.0 * (1.0 + u_local / np.sqrt(p_float))
        prime_gaps = np.diff(local_primes) if len(local_primes) > 1 else np.array([0])

        elapsed_ms = (time.perf_counter() - t0) * 1000.0

        pred_bounds = self.predict_spectral_global([max(2, x_start), x_start + delta_x])
        pred_window_annet = float(pred_bounds["pi_spec_fejer"][1] - pred_bounds["pi_spec_fejer"][0])
        pred_window_li = float(pred_bounds["pi_li_classic"][1] - pred_bounds["pi_li_classic"][0])

        return {
            "x_start": x_start,
            "delta_x": delta_x,
            "primes": local_primes,
            "u_local": u_local,
            "kappa_peaks": kappa_peaks,
            "prime_gaps": prime_gaps,
            "count_exact": len(local_primes),
            "pred_window_annet": pred_window_annet,
            "pred_window_li": pred_window_li,
            "elapsed_ms": elapsed_ms
        }

    def export_primes_proof_file(self, window_result: dict, filename: str = None) -> str:
        if filename is None:
            filename = f"Preuve_Premiers_Detectes_10e{self.k}_Annet.csv"

        primes = window_result["primes"]
        u_loc = window_result["u_local"]
        kappas = window_result["kappa_peaks"]

        with open(filename, mode="w", newline="", encoding="utf-8") as f:
            writer = csv.writer(f)
            writer.writerow([
                "# STANDARD JEAN-PHILIPPE ANNET (DOI: 10.5281/zenodo.23729257) - PREUVE DE DETECTION CELLULAIRE",
                f"Echelle x = 10^{self.k}",
                f"Fenetre [{window_result['x_start']}, {window_result['x_start'] + window_result['delta_x']}]",
                f"Total detecte = {window_result['count_exact']} nombres premiers",
                f"Temps = {window_result['elapsed_ms']:.2f} ms"
            ])
            writer.writerow([
                "Rang_dans_fenetre",
                "Nombre_Premier_p",
                "Coordonnee_Logarithmique_u_ln_p",
                "Capteur_Weyl_kappa_p",
                "Ecart_Gap_avec_precedent"
            ])
            for idx in range(len(primes)):
                gap = int(primes[idx] - primes[idx - 1]) if idx > 0 else 0
                writer.writerow([
                    idx + 1,
                    int(primes[idx]),
                    f"{u_loc[idx]:.10f}",
                    f"{kappas[idx]:.10f}",
                    gap
                ])
        return filename


